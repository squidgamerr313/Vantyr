/**
 * Capture a real wall-clock run of the unchanged production vision model.
 * Operator tool, not a camera accuracy test or a visitor-side inference loop.
 * Input/output binaries stay in ignored generated-artifacts and App Storage.
 */
import { chromium } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const dir = resolve('generated-artifacts/hero-engine-recording');
await mkdir(dir, { recursive: true });
const input = resolve(dir, 'input.mp4');
const hash = b => createHash('sha256').update(b).digest('hex');
const sourceHash = hash(await readFile(resolve(dir, 'source.mp4')));
const inputHash = hash(await readFile(input));
const base = `https://${process.env.REPLIT_DEV_DOMAIN}/`;
const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || '/repl/tools/bin/chromium',
  args: ['--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'],
});
const deadline = setTimeout(() => void browser.close(), 240000);
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
  await page.route('**/__hero_capture.html', r => r.fulfill({
    contentType: 'text/html',
    body: '<!doctype html><html><head><title>VANTYR recording operator</title></head><body style="margin:0;background:#111"></body></html>',
  }));
  await page.route('**/__hero_input.mp4', r => r.fulfill({ path: input, contentType: 'video/mp4' }));
  // Local IPC for generated bytes, never an application upload endpoint.
  await page.exposeFunction('saveHeroRecording', async base64 => {
    await writeFile(resolve(dir, 'capture.webm'), Buffer.from(base64, 'base64'));
  });
  await page.goto(`${base}__hero_capture.html`);
  const report = await page.evaluate(async () => {
    const { createVisionEngine } = await import('/src/lib/vision.ts');
    const { EVIDENCE_MAX_AGE_MS } = await import('/src/lib/monitoring-health.ts');
    const { createHeroRecordingRenderer } = await import('/scripts/hero-recording-renderer.ts');
    const media = document.createElement('video');
    media.muted = true; media.loop = true; media.src = '/__hero_input.mp4';
    document.body.append(media); await media.play();
    const stream = media.captureStream();
    const video = document.createElement('video');
    video.muted = true; video.srcObject = stream;
    document.body.append(video); await video.play();
    await new Promise(resolve => video.requestVideoFrameCallback(resolve));
    const canvas = document.createElement('canvas');
    canvas.width = 1600; canvas.height = 900;
    document.body.append(canvas);
    media.style.display = video.style.display = 'none';
    const renderer = createHeroRecordingRenderer(canvas);
    const statuses = [];
    const engine = await createVisionEngine(message => statuses.push(message));
    const analyses = [];
    const output = canvas.captureStream(24);
    const mime = 'video/webm;codecs=vp8';
    if (!MediaRecorder.isTypeSupported(mime)) throw Error('VP8 recording not available');
    const recorder = new MediaRecorder(output, { mimeType: mime, videoBitsPerSecond: 3_000_000 });
    const chunks = [];
    recorder.ondataavailable = event => { if (event.data.size) chunks.push(event.data); };
    let running = true, raf = 0, current = null, matched = null;
    // Observe the existing synchronous owned-frame capture, without changing
    // any engine/model code or prediction. Copy its canvas, not a second
    // independently sampled video frame.
    const nativeDraw = CanvasRenderingContext2D.prototype.drawImage;
    let observingCapture = false, captured = null;
    CanvasRenderingContext2D.prototype.drawImage = function (image, ...args) {
      nativeDraw.call(this, image, ...args);
      if (observingCapture && image === video &&
          this.canvas.width === video.videoWidth && this.canvas.height === video.videoHeight) {
        const copy = document.createElement('canvas');
        copy.width = this.canvas.width; copy.height = this.canvas.height;
        nativeDraw.call(copy.getContext('2d'), this.canvas, 0, 0);
        captured = copy;
      }
    };
    const start = performance.now();
    function draw() {
      renderer.draw(video, matched, current, performance.now() - start);
      if (running) raf = requestAnimationFrame(draw);
    }
    draw();
    recorder.start(500);
    const inference = (async () => {
      while (running) {
        const frameTimeMs = video.currentTime * 1000;
        const began = performance.now();
        captured = null;
        observingCapture = true;
        let work;
        try { work = engine.detect(video, frameTimeMs, began); }
        finally { observingCapture = false; }
        const snapshot = captured;
        const result = await work;
        if (!snapshot) throw Error('Actual owned input frame was not observed');
        const ended = performance.now();
        const accepted = ended - began < EVIDENCE_MAX_AGE_MS;
        analyses.push({ beganMs: began - start, completedMs: ended - start, accepted, result });
        if (running && accepted) { matched = snapshot; current = result; }
        // Do not fabricate output for expired frames.
        if (running && !accepted) { matched = null; current = null; }
        await new Promise(resolve => setTimeout(resolve, 80));
      }
    })();
    await new Promise(resolve => setTimeout(resolve, 20000));
    running = false; cancelAnimationFrame(raf);
    const stopped = new Promise(resolve => recorder.onstop = resolve);
    recorder.stop(); await stopped;
    await inference;
    CanvasRenderingContext2D.prototype.drawImage = nativeDraw;
    engine.dispose();
    stream.getTracks().forEach(t => t.stop()); output.getTracks().forEach(t => t.stop());
    media.pause(); video.pause();
    const blob = new Blob(chunks, { type: mime });
    const bytes = new Uint8Array(await blob.arrayBuffer());
    let binary = '';
    for (let i = 0; i < bytes.length; i += 16384) binary += String.fromCharCode(...bytes.subarray(i, i + 16384));
    await window.saveHeroRecording(btoa(binary));
    return { statuses, analyses, wallClockRecordingMs: 20000, inputWidth: video.videoWidth, inputHeight: video.videoHeight };
  });
  if (!report.analyses.some(s => s.accepted && s.result.detections.length))
    throw Error('No real detections captured; do not publish an empty or fabricated demonstration');
  await writeFile(resolve(dir, 'provenance.json'), JSON.stringify({
    recordedAt: new Date().toISOString(),
    source: {
      page: 'https://www.pexels.com/video/a-woman-walking-inside-the-house-4098697/',
      url: 'https://videos.pexels.com/video-files/4098697/4098697-hd_1920_1080_30fps.mp4',
      author: 'Martina Tomšič', license: 'https://www.pexels.com/license/',
      sourceSha256: sourceHash, preparedInputSha256: inputHash,
      use: 'Ordinary walking only; no harm, intent, endorsement or field-accuracy claims',
    },
    mode: 'Actual production createVisionEngine balanced profile, wall-clock recording, no retiming',
    inputMatching: 'Analysed image copied directly from the actual owned inference canvas; no independently sampled or interpolated frames',
    graphics: 'Chromium ANGLE SwiftShader software graphics; not a device performance benchmark',
    engineSourceSha256: hash(await readFile('artifacts/safesight/src/lib/vision.ts')),
    ...report,
  }, null, 2));
  console.log(JSON.stringify({
    framesAnalysed: report.analyses.length,
    accepted: report.analyses.filter(s => s.accepted).length,
    withPeople: report.analyses.filter(s => s.result.detections.some(d => d.label === 'person')).length,
    withPose: report.analyses.filter(s => s.result.landmarks.length).length,
  }));
} finally { clearTimeout(deadline); await browser.close(); }
